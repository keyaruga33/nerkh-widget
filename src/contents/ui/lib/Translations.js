// ── Translation Helper ──
function t(lang, key, args) {
    var table = STRINGS[lang] || STRINGS.en
    var s = (key in table) ? table[key] : (STRINGS.en[key] || key)
    if (args !== undefined) {
        var list = Array.isArray(args) ? args : [args]
        for (var i = 0; i < list.length; ++i)
            s = s.replace("%" + (i + 1), list[i])
    }
    return s
}
